'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=path=>fs.readFileSync(path,'utf8');
const client=read('backend/src/Integrations/KavenegarSms.php');
const router=read('backend/src/Integrations/SmsProvider.php');
const api=read('backend/public/index.php');
const sms=read('backend/src/Auth/SmsLogin.php');
const recovery=read('backend/src/Auth/PasswordRecovery.php');
const policy=read('backend/src/Auth/LoginMethods.php');
const queue=read('backend/src/Integrations/SmsQueue.php');
const ui=read('frontend/assets/login-methods.js');
const css=read('frontend/assets/filter-consistency.css');
for(const key of ['kavenegar_api_key_enc','kavenegar_sender','kavenegar_enabled'])assert.ok(client.includes(key),'Missing Kavenegar setting '+key);
assert.ok(client.includes('NeginSms::encryptProviderSecret'),'API keys must be encrypted at rest');
assert.ok(client.includes('NeginSms::decryptProviderSecret'),'Stored API keys must be decrypted server-side only');
assert.ok(client.includes('Authorization::isSuperAdmin($actor)'),'Credentials restricted to super admin');
assert.ok(!client.includes("'apiKey'=>$c['key']"),'No secret may be returned to browser');
assert.ok(client.includes('CURLOPT_SSL_VERIFYPEER=>true')&&client.includes('CURLOPT_SSL_VERIFYHOST=>2'),'HTTPS certificates must be validated');
assert.ok(client.includes('CURLOPT_FOLLOWLOCATION=>false'),'Never leak API key in redirected URL');
assert.ok(client.includes('CURLOPT_CONNECTTIMEOUT=>8')&&client.includes('CURLOPT_TIMEOUT=>25'),'Bound external network requests');
assert.ok(client.includes('https://api.kavenegar.com/v1/'),'Official first-party REST endpoint used');
assert.ok(router.includes("sms_provider_selected")&&router.includes("return 'negin'"),'Existing tenants default to Negin');
assert.ok(router.includes('KavenegarSms::ready()')&&router.includes('NeginSms::ready()'),'Only selected ready provider can send');
assert.ok(router.includes('catch(AuthException $e)')&&router.includes('configurationError'), 'Corrupted inactive provider credentials must not block admin recovery');
assert.ok(!router.slice(router.indexOf('public function send(')).includes('catch('),'Send route must not silently fall back on uncertain sends');
assert.ok(api.includes("'/api/v1/admin/kavenegar-sms'")&&api.includes("'/api/v1/admin/sms-provider-selection'"),'Super-admin Kavenegar and switch endpoints registered');
assert.ok(api.includes('KavenegarSms::configure')&&api.includes('SmsProvider::configure'),'Settings calls use authorized domain methods');
assert.ok(sms.includes('(new SmsProvider())->send')&&recovery.includes('(new SmsProvider())->send'),'All OTP and recovery sends use selected provider');
assert.ok(policy.includes('$smsReady=SmsProvider::ready()'),'Login method readiness matches active provider');
assert.ok(queue.includes('new SmsProvider()'),'Queued SMS must respect selected provider');
assert.ok(ui.includes('syAdminKavenegarSms')&&ui.includes('/api/v1/admin/kavenegar-sms'),'Kavenegar UI is accessible from super admin');
assert.ok(ui.includes('/api/v1/admin/sms-provider-selection')&&ui.includes("X-CSRF-Token"),'Active SMS selector must use CSRF');
assert.ok(css.includes('.sy-sms-provider-grid')&&css.includes('max-width:480px'),'Provider UI is compact and responsive');
console.log('Kavenegar provider security and SMS integration contracts: OK');
