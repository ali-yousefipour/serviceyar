'use strict';
/* Nonvisual style contract. Pixel-perfect device/browser checks remain separate. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const get=name=>fs.readFileSync(name,'utf8');
const html=get('frontend/index.html');
const base=get('frontend/assets/app.css');
const portal=get('frontend/assets/portal.css');
const styles=get('frontend/assets/ui-consistency.css');
const theme=get('frontend/assets/brand-theme.css');
const vendor=get('frontend/assets/leaflet.css');
assert.ok(html.includes('ui-consistency.css?v=__BUILD_ID__'), 'Shared UI styles must be released with the build identifier');
assert.ok(html.includes('rel="preload" href="/assets/Vazirmatn-Regular.woff2?v=20261014-1" as="font" type="font/woff2" crossorigin'), 'The locally served font should be preloaded for first paint');
assert.ok(html.indexOf('ui-consistency.css')>html.indexOf('brand-theme.css'),'Shared UI overrides must follow the institutional theme');
assert.ok(html.indexOf('ui-consistency.css')>html.indexOf('portal.css'),'Shared UI overrides must follow portal styles');
assert.match(base,/@font-face\{font-family:Vazirmatn;[^}]+font-weight:400;/,'Bundled static Vazirmatn must not claim to be a variable weight font');
assert.doesNotMatch(portal,/@font-face\s*\{/, 'Portal must not register a duplicate font face');
assert.match(styles,/--sy-ui-body:\.875rem/, 'Readable 14px base text token must be shared');
assert.match(styles,/--sy-ui-small:\.8125rem/, 'Compact text token must remain at least 13px');
assert.match(styles,/#app \.sy-admin-page-card table/, 'Admin tables must have a dedicated legible font override');
assert.match(styles,/#app \.sy-admin-page-heading/, 'Super-admin section heading must wrap on mobile');
assert.match(styles,/#app \.sy-admin-page-card :is\(th,td\)/, 'Mobile admin cells must keep readable sizes');
assert.ok(styles.includes('.table-wrap:has(thead th:nth-child(5)) table{min-width:max(42rem,100%);}'), 'Only genuinely wide admin tables should scroll on mobile');
assert.match(styles,/#app\.sy-portal-mode \.portal-panel :is\(th,td\)/, 'Parent and driver tables must share the readable type scale');
assert.match(styles,/#app \.sy-invoice-table :is\(th,td\)/, 'Invoice tables must share the readable type scale');
assert.match(styles,/#app \.solar-date-field/, 'Jalali calendar controls must fit narrow screens');
assert.match(styles, /@media screen and \(max-width:760px\)/, 'Mobile responsive design at tablet breakpoint is missing');
assert.match(styles, /@media screen and \(max-width:480px\)/, 'Small phone breakpoint is missing');
assert.match(styles, /#login \.sy-login-method-tab/, 'Login methods must use legible mobile type and touch targets');
assert.match(styles, /#app :is\(\.pager,\.member-actions,\.row-actions\)/, 'Pagination and row controls need consistent type scale');
assert.match(styles, /prefers-reduced-motion:reduce/, 'Reduced motion support is required');
assert.match(styles, /:focus-visible/, 'Keyboard focus must remain visible');
assert.match(styles, /@media screen\{/, 'Interactive-screen overrides must not change PDF print layouts');
assert.doesNotMatch(styles, /(?:^|\n)\s*\.leaflet-marker-icon\s*\{/, 'Do not overwrite vendor map marker layout');
assert.ok(theme.includes('.sy-admin-page-card table{width:100%') && theme.includes('font:500 10px'), 'This test protects the measured previous admin font size regression');
assert.ok(vendor.includes('.leaflet-container'), 'Leaflet remains a separately scoped vendor asset');
console.log('Cross-panel RTL typography and responsive visual contracts: OK');
