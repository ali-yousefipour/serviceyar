'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const operations=fs.readFileSync('backend/src/Domain/OperationsService.php','utf8');
const documents=fs.readFileSync('backend/src/Domain/PayrollDocuments.php','utf8');
const ui=fs.readFileSync('frontend/assets/operations.js','utf8');
const start=operations.indexOf('public static function payroll(');
const end=operations.indexOf('public static function driverDeductions(',start);
assert.ok(start>=0&&end>start,'Payroll method must exist');
const payroll=operations.slice(start,end);
assert.match(payroll,/driver_work w[\s\S]*?work_date BETWEEN :wf AND :wt/,'Earnings remain period-bound driver_work');
assert.match(payroll,/JOIN service_students ss ON ss.service_id=s.id/,'Reference uses service assignments');
assert.match(payroll,/JOIN students st ON st.id=ss.student_id AND st.agency_id=s.agency_id/,'Assignments are tenant-scoped');
assert.match(payroll,/s.is_active=1 AND st.is_active=1/,'Reference excludes inactive students and services');
assert.match(payroll,/COALESCE\(st.driver_base_monthly,st.monthly_fee\)/,'Use driver base, not parent tuition alone');
assert.match(payroll,/\$gross=\(float\)\$r\['earned'\]/,'Payroll continues from recorded work');
assert.match(payroll,/\$r\['assigned_monthly_net'\]/,'Monthly reference net exposed');
assert.match(payroll,/\$r\['work_vs_assigned_monthly_delta'\]/,'Reconciliation delta exposed');
assert.doesNotMatch(payroll,/\b(?:UPDATE|INSERT INTO|DELETE FROM)\s+(?:driver_work|payroll_documents|payroll_document_lines)\b/i,'Reconciliation must not rewrite historical records');
assert.match(documents,/if\(\$status!=='draft'\)throw new AuthException\(409,'سند تأییدشده قابل تغییر نیست/,'Approved payroll remains locked');
assert.match(ui,/r\.assigned_monthly_base/,'UI shows monthly assignment reference');
assert.match(ui,/r\.work_vs_assigned_monthly_delta/,'UI shows non-authoritative discrepancy');
assert.match(ui,/اختلاف آن بدهی قطعی محسوب نمی‌شود/,'UI warns against equating different periods');
console.log('Payroll read-only reconciliation contract passed');
