'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const loader=read('frontend/assets/task-progress.js');
const style=read('frontend/assets/task-progress.css');
const html=read('frontend/index.html');
const app=read('frontend/assets/app.js');
const operations=read('frontend/assets/operations.js');
const portal=read('frontend/assets/portal.js');
assert.ok(html.indexOf('task-progress.js')<html.indexOf('app.js'),'Progress controller must load before app');
assert.match(html,/task-progress\.css\?v=__BUILD_ID__/,'Progress CSS must be cache-busted by deployment');
assert.match(loader,/Number\.isSafeInteger\(length\)&&length>0/,'Download % must require a measured content length');
assert.match(loader,/received\/length\*100/,'Download percent must use received bytes, not elapsed time');
assert.match(loader,/!response\.headers\.get\('content-encoding'\)/,'Do not misreport compressed transfer bytes');
assert.match(loader,/percent:measurable\?Math\.min\(99,received\/length\*100\):null/,'Unknown download length must not produce fabricated percentages');
assert.match(loader,/finally\{task\.finish\(\);\}/,'Progress state must clean up on failure');
assert.match(app,/ServiceYarLoading\?\.begin/,'Admin API must show shared progress');
assert.match(app,/ServiceYarLoading\.download\('\/api\/v1\/reports\/export/,'Main Excel export must use shared downloader');
assert.match(operations,/async function downloadFile\(url,name\)[\s\S]*?ServiceYarLoading\.download/,'Operations exports must use shared downloader');
assert.match(operations,/onProgress\(\+\+completedPages,totalPages\)/,'PDF progress must count completed rendered pages');
assert.match(operations,/percent:count>0\?Math\.min\(99,Math\.round\(index\/count\*100\)\):null/,'PDF percentage must use measured completed pages');
assert.match(operations,/ServiceYarLoading\?\.begin\('ساخت فایل PDF فیش حقوقی'/,'Payslip generation must show a loading state');
assert.match(portal,/ServiceYarLoading\?\.begin/,'Parent and driver portal must show loading');
assert.match(loader,/xhr\.upload\.onprogress=event=>/,'Upload percentage must come from actual XHR progress');
assert.match(loader,/event\.lengthComputable&&event\.total>0/,'Unknown upload length must not display percentages');
assert.match(loader,/percent:null/,'Server processing must revert to indeterminate state');
assert.match(operations,/ServiceYarLoading\.upload\(scoped\('\/api\/v1\/operations\/import\/preview'/,'Student import must use measured upload progress');
assert.match(portal,/ServiceYarLoading\.upload\(endpoint,body/,'Driver portrait upload must report measured bytes');
assert.match(style,/@media\(max-width:520px\)/,'Progress must fit mobile screens');
assert.match(style,/prefers-reduced-motion:reduce/,'Loading animation must respect reduced-motion');
console.log('Shared loading and real progress contract: OK');
