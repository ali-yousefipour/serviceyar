'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../frontend/assets/operations.js'),'utf8');
const start=source.indexOf(' const normalizeAccount=value=>',source.indexOf('async function accountStatementPage('));
const end=source.indexOf(" $('statementSearch').oninput",start);
assert(start>=0&&end>start,'Account search normalizer missing');
const context={};
vm.runInNewContext(source.slice(start,end)+'\nthis.normalizeAccount=normalizeAccount;',context);
assert.equal(context.normalizeAccount('  حساب‌   بانک  '),'حساب بانک');
assert.equal(context.normalizeAccount('كارت يار'),'کارت یار');
assert.equal(context.normalizeAccount('حساب ۱۲۳'),'حساب 123');
assert.equal(context.normalizeAccount('حساب ١٢٣'),'حساب 123');
assert.equal(context.normalizeAccount('abc ۱۲۳'),context.normalizeAccount('ABC 123'));
assert(source.includes("request++;form.reset();"),'Reset must invalidate earlier financial response');
assert(source.includes("if(filters.from&&filters.to&&filters.to<filters.from)"),'Reverse date range must be rejected');
assert(source.includes('sy-account-statement-table'),'Statement table should preserve mobile labels');
console.log('Accounting account search and safe report filters passed');
