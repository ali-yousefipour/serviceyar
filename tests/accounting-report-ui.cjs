'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../frontend/assets/operations.js'),'utf8');
const start=source.indexOf(' const normalizeAccount=value=>',source.indexOf('async function accountStatementPage('));
const end=source.indexOf(" $('statementSearch').oninput",start);
assert(start>=0&&end>start,'Account search normalizer missing');
const context={};
vm.runInNewContext(source.slice(start,end)+'\nthis.normalizeAccount=normalizeAccount;',context);
assert.equal(context.normalizeAccount('  حساب‌   بانک  '),'حساب بانک');
assert.equal(context.normalizeAccount('كارت يار'),'کارت یار');
assert.equal(context.normalizeAccount('حساب ۱۲۳'),'حساب 123');
assert.equal(context.normalizeAccount('حساب ١٢٣'),'حساب 123');
assert.equal(context.normalizeAccount('abc ۱۲۳'),context.normalizeAccount('ABC 123'));
assert(source.includes("request++;form.reset();"),'Reset must invalidate earlier financial response');
assert(source.includes("if(filters.from&&filters.to&&filters.to<filters.from)"),'Reverse date range must be rejected');
assert(source.includes('sy-account-statement-table'),'Statement table should preserve mobile labels');
assert(source.includes('id="statementPrint"'),'Account statement should have a dedicated print button');
assert(source.includes("$('statementPrint')?.addEventListener('click',()=>window.print())"),'Report print action should be wired');
assert(source.includes('چاپ صفحه فعلی'),'Printed report must clearly identify its pagination scope');
assert(source.includes('خروجی اکسل (کل بازه)'),'Export should clearly identify its full-range scope');
assert(source.includes('class="panel sy-quick-journal"'),'Quick journal should use the dedicated guided layout');
for(const section of ['quickPeopleTitle','quickDocumentTitle','quickRowsTitle'])assert(source.includes('aria-labelledby="'+section+'"'),'Quick journal section '+section+' must be labelled');
assert(source.includes('id="quickJournalHint"'),'Quick journal must explain why saving is unavailable');
assert(source.includes('sy-quick-table-wrap" tabindex="0" role="region"'),'Quick journal person table must have a keyboard-scrollable region');
assert(source.includes('data-label="مبلغ · ریال"'),'Quick journal mobile rows must preserve column names');
console.log('Accounting account search and safe report filters passed');
